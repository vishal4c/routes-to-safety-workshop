#!/usr/bin/env python3
"""Regenerate 02-web/solution.html from 02-web/index.html.
solution.html = index.html with every dataset preloaded (all four steps, reach rings, routing).
Run after editing index.html:  python3 scripts/make-solution.py
"""
import pathlib, sys
R = pathlib.Path(__file__).resolve().parent.parent; w = R / '02-web'
src = (w / 'index.html').read_text()
def rep(s, o, n):
    if o not in s: sys.exit(f'make-solution: anchor not found: {o[:60]!r}')
    return s.replace(o, n, 1)
sol = rep(src, "const PRELOAD = { tiles: false, steps: [], reach: false, routing: false };", "const PRELOAD = { tiles: true, steps: [1, 2, 3, 4], reach: true, routing: true };")
sol = rep(sol, "<title>Routes to Safety — Placer I-80 corridor</title>", "<title>Routes to Safety — Placer I-80 corridor (SOLUTION)</title>")
sol = rep(sol, '<div id="map"></div>', '<!-- BAIL-OUT FILE, generated by scripts/make-solution.py: index.html with all four steps, the reach rings and routing preloaded. Open this if you are behind; otherwise work in index.html. -->\n<div id="map"></div>')
(w / 'solution.html').write_text(sol); print('wrote 02-web/solution.html', len(sol), 'bytes')
