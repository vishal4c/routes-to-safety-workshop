#!/usr/bin/env python3
"""Regenerate 02-web/solution.html from 02-web/index.html + steps/step4-final.json.
solution.html = index.html with step 4 pasted, the attribution control on and 03-routing/route.js imported.
Run after editing index.html or step4-final.json:  python3 scripts/make-solution.py
"""
import pathlib, sys
R = pathlib.Path(__file__).resolve().parent.parent; w = R / '02-web'
src = (w / 'index.html').read_text()
step4 = (w / 'steps/step4-final.json').read_text().strip()
def rep(s, o, n):
    if o not in s: sys.exit(f'make-solution: anchor not found: {o[:60]!r}')
    return s.replace(o, n, 1)
sol = rep(src, "const STEP4 = [];", "const STEP4 = " + step4 + ";")
sol = rep(sol, "// map.addControl(new maplibregl.AttributionControl({ compact: false,\n//   customAttribution", "map.addControl(new maplibregl.AttributionControl({ compact: false,\n  customAttribution")
sol = rep(sol, "// }), 'bottom-right');", "}), 'bottom-right');")
sol = rep(sol, "  // import('../03-routing/route.js')", "  import('../03-routing/route.js')")
sol = rep(sol, "<title>Routes to Safety — Placer I-80 corridor</title>", "<title>Routes to Safety — Placer I-80 corridor (SOLUTION)</title>")
sol = rep(sol, '<div id="map"></div>', '<!-- BAIL-OUT FILE, generated by scripts/make-solution.py: index.html with steps/step4-final.json pasted,\n     attribution on, and 03-routing/route.js imported. Open this if you are behind; otherwise work in index.html. -->\n<div id="map"></div>')
(w / 'solution.html').write_text(sol); print('wrote 02-web/solution.html', len(sol), 'bytes')
